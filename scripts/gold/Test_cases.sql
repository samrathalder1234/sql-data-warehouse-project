-- Calculate total sales each month
SELECT 
	month_of_sale,
	total_sales,
	SUM(total_sales) OVER (PARTITION BY YEAR(month_of_sale) ORDER BY month_of_sale) AS running_total_sales,
	AVG(avg_price) OVER (ORDER BY month_of_sale) AS moving_average_price
FROM (
SELECT 
	DATETRUNC(MONTH, order_date) AS month_of_sale,
	SUM(sales) AS total_sales,
	AVG(price) AS avg_price
FROM gold.fact_sales
WHERE order_date IS NOT NULL
GROUP BY DATETRUNC(MONTH, order_date)
) t

/* Analyze the yearly performance of products by comparing their sales
to both the average sales performance of the product and previous year's sales*/
WITH yearly_product_sales AS (
SELECT
	YEAR(s.order_date) AS order_year,
	p.product_name,
	SUM(s.sales) as current_sales
FROM gold.fact_sales s
LEFT JOIN gold.dim_products p
ON s.product_key = p.product_key
WHERE s.order_date IS NOT NULL
GROUP BY YEAR(s.order_date), p.product_name
)
SELECT 
	order_year,
	product_name,
	current_sales,
	AVG(current_sales) OVER (PARTITION BY product_name) AS avg_sales,
	current_sales - AVG(current_sales) OVER (PARTITION BY product_name) AS diff_avg,
	CASE
		WHEN current_sales - AVG(current_sales) OVER (PARTITION BY product_name) < 0 THEN 'Below avg'
		WHEN current_sales - AVG(current_sales) OVER (PARTITION BY product_name) > 0 THEN 'Above avg'
		ELSE 'Avg'
	END AS avg_change,
	-- Year over Year Analysis
	LAG(current_sales) OVER (PARTITION BY product_name ORDER BY order_year) AS prev_year_sales,
	current_sales - LAG(current_sales) OVER (PARTITION BY product_name ORDER BY order_year) AS diff_sales,
	CASE
		WHEN current_sales - LAG(current_sales) OVER (PARTITION BY product_name ORDER BY order_year) < 0 THEN 'Increasing'
		WHEN current_sales - LAG(current_sales) OVER (PARTITION BY product_name ORDER BY order_year) > 0 THEN 'Decreasing'
		ELSE 'No Change'
	END AS py_change
FROM yearly_product_sales
ORDER BY product_name, order_year	


-- Which category contributes most to overall sales
WITH category_sales AS (
SELECT
	category,
	SUM(sales) AS sales
FROM gold.fact_sales s
LEFT JOIN gold.dim_products p
ON s.product_key = p.product_key
GROUP BY category
)
SELECT 
	category,
	sales,
	SUM(sales) OVER () AS total_sales,
	CONCAT(ROUND((CAST(sales AS FLOAT)/SUM(sales) OVER ())*100, 2), '%') AS percentage_of_total
FROM category_sales
ORDER BY sales DESC


/* Segment products into cost ranges and
count how many products fall into each segment */
WITH product_segments AS (
SELECT 
	product_key,
	product_name,
	cost,
	CASE
		WHEN cost < 100 THEN 'Below 100'
		WHEN cost BETWEEN 100 AND 500 THEN '100-500'
		WHEN cost BETWEEN 500 AND 1000 THEN '500-1000'
		ELSE 'Above 1000'
	END AS cost_range
FROM gold.dim_products)

SELECT
	cost_range,
	COUNT(product_key) AS product_count
FROM product_segments
GROUP BY cost_range
ORDER BY product_count DESC


/* Group customers into 3 segments based on their spending behavior
	- VIP: atleast 12 months of history and spending > 5000
	- Regular: atleast 12 months of history but spending < 5000
	- New: lifespan < 12 months
	Also find the total number of customers in each group
*/
	WITH customer_segments AS (
	SELECT 
		c.customer_key,
		SUM(s.sales) AS total_sales,
		MIN(order_date) AS first_order,
		MAX(order_date) AS last_order,
		DATEDIFF(month, MIN(order_date) ,MAX(order_date)) AS lifespan
	FROM gold.fact_sales s
	LEFT JOIN gold.dim_customers c
	ON s.customer_key = c.customer_key
	GROUP BY c.customer_key)

	SELECT
		segments,
		COUNT(customer_key) customer_count
	FROM (
	SELECT 
		customer_key,
		CASE
			WHEN total_sales > 5000 AND lifespan >= 12 THEN 'VIP'
			WHEN total_sales < 5000 and lifespan >= 12 THEN 'Regular'
			ELSE 'New'
		END AS segments
	FROM customer_segments
	) t 
	GROUP BY segments
	ORDER BY customer_count DESC


